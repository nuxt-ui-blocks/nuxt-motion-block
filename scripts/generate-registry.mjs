// Generates src/registry.generated.ts — a static map of M-name -> lazy SFC importer.
// Committed: deterministic from src/runtime/components.
import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = 'src/runtime/components'
const list = []

function pascal(segment) {
  return segment.split(/[-_\s]/).map(p => p ? p[0].toUpperCase() + p.slice(1) : '').join('')
}

function nameOf(rel) {
  const parts = rel.replace(/\.vue$/, '').split('/').filter(Boolean).map(pascal)
  while (parts.length >= 2 && parts[parts.length - 1] === parts[parts.length - 2]) parts.pop()
  return parts.join('')
}

function walk(dir, relPrefix) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    const rel = relPrefix ? relPrefix + '/' + entry.name : entry.name
    if (entry.isDirectory()) {
      walk(full, rel)
      continue
    }
    if (!entry.name.endsWith('.vue')) continue
    list.push({ rel: rel.replace(/\\/g, '/'), name: nameOf(rel) })
  }
}

walk(root, '')

const body = list
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(c => `  { name: 'M${c.name}', component: () => import('./runtime/components/${c.rel}') },`)
  .join('\n')

const file = `// AUTO-GENERATED by scripts/generate-registry.mjs - do not edit by hand.
import type { Component } from 'vue'

export interface RegisteredComponent {
  name: string
  component: () => Promise<{ default: Component }>
}

export const registry: RegisteredComponent[] = [
${body}
]
`

writeFileSync('src/registry.generated.ts', file)
console.log(`registry: ${list.length} components`)
