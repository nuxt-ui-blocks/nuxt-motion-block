import { readdirSync, writeFileSync } from 'node:fs'
import { resolve, join } from 'node:path'

const repoRoot = resolve(import.meta.dirname, '..', '..')
const componentsDir = resolve(repoRoot, 'src', 'runtime', 'components')
const outFile = resolve(import.meta.dirname, '..', 'app', 'components', 'content', 'playground-components.ts')

const REL_PREFIX = '../../../../src/runtime/components'

function pascalCase(segment) {
  return segment
    .split(/[-_]/)
    .filter(Boolean)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

/**
 * Mirrors Nuxt's component auto-naming (src/module.ts registers the whole
 * `components/` tree with `addComponentsDir`, prefix `M`), so every public name
 * the docs can reference resolves here too:
 *   - path segments are PascalCased and concatenated,
 *   - a segment that repeats the previous one collapses (`Accordion/Accordion.vue`
 *     -> `Accordion`, so the public component is `MAccordion`, not
 *     `MAccordionAccordion`).
 * The registry stores the *unprefixed* name, matching `<ComponentPlayground name="…">`.
 */
function componentName(relPath) {
  const segments = relPath.replace(/\.vue$/, '').split('/')
  const out = []
  for (const segment of segments) {
    const part = pascalCase(segment)
    if (!part) continue
    if (out.length && out[out.length - 1] === part) continue
    out.push(part)
  }
  return out.join('')
}

const entries = []

function walk(dir, prefix) {
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name
    if (e.isFile() && e.name.endsWith('.vue')) {
      entries.push({ name: componentName(rel), path: rel })
    }
    else if (e.isDirectory()) {
      walk(join(dir, e.name), rel)
    }
  }
}

walk(componentsDir, '')

const byName = new Map()
const duplicates = []
for (const entry of entries) {
  if (byName.has(entry.name)) duplicates.push(`${entry.name} (${byName.get(entry.name).path} vs ${entry.path})`)
  else byName.set(entry.name, entry)
}

if (duplicates.length) {
  console.error(`Duplicate component names:\n${duplicates.join('\n')}`)
  process.exit(1)
}

const sorted = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name))
// Aliased imports: a public name may start with a digit (`3DCard`), which is not
// a legal JS identifier, so every import binds to an index-safe local name and the
// public name lives only as the object key.
const imports = sorted.map((n, i) => `import c${i} from '${REL_PREFIX}/${n.path}'`)
const list = sorted.map((n, i) => `  '${n.name}': c${i},`)

const content = `// AUTO-GENERATED by docs/scripts/gen-playground-registry.mjs — do not edit by hand.
// @ts-nocheck
${imports.join('\n')}

export const playgroundComponents: Record<string, any> = {
${list.join('\n')}
}

export const playgroundComponentNames: string[] = [
${sorted.map(n => `  '${n.name}',`).join('\n')}
]
`

writeFileSync(outFile, content, 'utf8')
console.log(`Wrote ${sorted.length} components -> ${outFile}`)
